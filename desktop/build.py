#!/usr/bin/env python3
"""MOD-014 — deterministic single-file build for the Wallpaper Engine desktop plugin.

Concatenates every ``*.js`` under ``desktop/src/`` (sorted by filename) into one
``desktop/plugin.js`` which the Hermes runtime loader evaluates as a single ESM
module from a blob URL.

Why a single file (hard constraint, not a preference): the runtime import
whitelist is an exact-string match on 4 keys (design F2), and the module is
evaluated via ``URL.createObjectURL(new Blob([...]))`` with no filesystem base
URL, so sibling resolution is impossible by construction. A ``./10-layer.js``
specifier is rejected by the loader, therefore "multiple source files" can only
exist at build time.

Rules enforced (design §3.1, MOD-014). Violations abort the build with a
non-zero exit code and an explicit message naming file, line and offending
content — never a silent pass:

  rule1  00-core.js is the ONLY file allowed to ``import``; its imports must sit
         at the top of the file (only comments/blank lines before them) and every
         specifier must be one of the 4 whitelisted keys.
  rule2  every other file may only declare top-level ``function`` / ``const``:
         no ``import`` (static or dynamic), no ``export``.
  rule3  99-register.js must sort last and hold the single ``export default``.
  rule4  the first output line is ``// GENERATED by build.py — do not edit``.
  rule5  files collaborate through the global scope only (no module boundary);
         symbols are ``we``-prefixed by convention. NOTE: prefix conformance is a
         review convention and is intentionally NOT machine-enforced here (a
         regex over identifiers would false-positive on locals, properties and
         JSX); the structural rules above are the enforced part.
  rule6  output is UTF-8 + LF only (CRLF/CR in sources is normalised); the
         sha256 of the written bytes is printed on the last line as
         ``sha256: <hex>`` so two runs can be diffed mechanically.
  rule7  everything else under ``desktop/`` is copied wholesale by Electron
         (F4) but never executed — ``src/`` is build input, not runtime layout.

Usage:
    python build.py [--src DIR] [--out FILE]

Exit codes: 0 = built, 1 = rule/source violation, 2 = argparse usage error.
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

HEADER = "// GENERATED by build.py — do not edit"

CORE_FILE = "00-core.js"
REGISTER_FILE = "99-register.js"

# Design F2: the loader whitelist is 4 exact keys, nothing else.
ALLOWED_SPECIFIERS = (
    "@hermes/plugin-sdk",
    "react",
    "react/jsx-runtime",
    "react/jsx-dev-runtime",
)

DESKTOP_DIR = Path(__file__).resolve().parent
DEFAULT_SRC = DESKTOP_DIR / "src"
DEFAULT_OUT = DESKTOP_DIR / "plugin.js"

# --- signal patterns -------------------------------------------------------

# Static import statement: `import x from "s"`, `import {a} from "s"`,
# `import * as ns from "s"`, `import "s"`, and multi-line variants (no `;` may
# intervene). `import(` never matches because whitespace is required after the
# keyword, so dynamic import is detected separately.
_STATIC_IMPORT = re.compile(
    r"""(?ms)^[ \t]*import\s+(?:[^;]*?\bfrom\s*)?["'](?P<spec>[^"'\n]+)["']"""
)
_DYNAMIC_IMPORT = re.compile(r"(?m)\bimport\s*\(")
_EXPORT_LINE = re.compile(r"(?m)^[ \t]*export\b")
_EXPORT_DEFAULT = re.compile(r"(?m)^[ \t]*export\s+default\b")
_LINE_COMMENT = re.compile(r"//[^\n]*")
_BLOCK_COMMENT = re.compile(r"/\*[\s\S]*?\*/")


class BuildError(Exception):
    """Raised for any rule violation or unreadable source."""


def _lineno(text: str, index: int) -> int:
    return text.count("\n", 0, index) + 1


def _snippet(text: str, index: int, limit: int = 120) -> str:
    """Single-line, whitespace-collapsed excerpt starting at ``index``."""
    end = text.find("\n", index)
    if end == -1:
        end = len(text)
    line = " ".join(text[index:end].split())
    if len(line) > limit:
        line = line[: limit - 1] + "…"
    return line


def _strip_comments(fragment: str) -> str:
    return _LINE_COMMENT.sub("", _BLOCK_COMMENT.sub("", fragment)).strip()


def _violation(name: str, line: int, rule: str, message: str) -> str:
    return f"{name}:{line}: [{rule}] {message}"


def discover_sources(src: Path) -> list[Path]:
    """Return ``src/*.js`` sorted by filename (non-recursive, no subdirs)."""
    if not src.is_dir():
        raise BuildError(f"source directory not found: {src}")
    files = sorted(
        (p for p in src.iterdir() if p.is_file() and p.suffix == ".js"),
        key=lambda p: p.name,
    )
    if not files:
        raise BuildError(f"no *.js files in {src}")

    names = [p.name for p in files]
    if CORE_FILE not in names:
        raise BuildError(
            f"{CORE_FILE} is missing from {src} "
            f"({_violation(CORE_FILE, 0, 'rule1', 'required: the only file allowed to import')})"
        )
    if REGISTER_FILE not in names:
        raise BuildError(
            f"{REGISTER_FILE} is missing from {src} "
            f"({_violation(REGISTER_FILE, 0, 'rule3', 'required: holds the single export default')})"
        )
    if names[-1] != REGISTER_FILE:
        raise BuildError(
            _violation(
                REGISTER_FILE,
                0,
                "rule3",
                f"must be the last file by filename order, but {names[-1]!r} sorts after it "
                f"(order: {', '.join(names)})",
            )
        )
    return files


def read_source(path: Path) -> str:
    """Read as UTF-8, drop BOM, normalise CRLF/CR to LF."""
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise BuildError(
            _violation(path.name, 0, "rule6", f"not valid UTF-8: {exc}")
        ) from exc
    if text.startswith("\ufeff"):
        text = text[1:]
    return text.replace("\r\n", "\n").replace("\r", "\n")


def validate_source(name: str, text: str, is_core: bool) -> list[str]:
    """Collect every structural violation of rules 1/2/3 for one source file."""
    problems: list[str] = []

    if not is_core:
        # rule2: no import, static or dynamic.
        for match in _STATIC_IMPORT.finditer(text):
            problems.append(
                _violation(
                    name,
                    _lineno(text, match.start()),
                    "rule2",
                    "import is only allowed in "
                    f"{CORE_FILE}, found: {_snippet(text, match.start())}",
                )
            )
        for match in _DYNAMIC_IMPORT.finditer(text):
            problems.append(
                _violation(
                    name,
                    _lineno(text, match.start()),
                    "rule2",
                    f"dynamic import() is not allowed in a concatenated plugin: "
                    f"{_snippet(text, match.start())}",
                )
            )
    else:
        # rule1: dynamic import is never part of the whitelist story.
        for match in _DYNAMIC_IMPORT.finditer(text):
            problems.append(
                _violation(
                    name,
                    _lineno(text, match.start()),
                    "rule1",
                    "dynamic import() is not allowed (whitelist is static only): "
                    f"{_snippet(text, match.start())}",
                )
            )
        # rule1: specifiers must be one of the 4 exact whitelist keys.
        for match in _STATIC_IMPORT.finditer(text):
            spec = match.group("spec")
            if spec not in ALLOWED_SPECIFIERS:
                problems.append(
                    _violation(
                        name,
                        _lineno(text, match.start()),
                        "rule1",
                        f"specifier {spec!r} is not whitelisted; allowed: "
                        f"{', '.join(ALLOWED_SPECIFIERS)} — offending line: "
                        f"{_snippet(text, match.start())}",
                    )
                )
        # rule1: imports must sit at the very top (comments/blank lines only).
        first_import = _STATIC_IMPORT.search(text)
        if first_import is not None:
            prefix = _strip_comments(text[: first_import.start()])
            if prefix:
                problems.append(
                    _violation(
                        name,
                        _lineno(text, first_import.start()),
                        "rule1",
                        "import must be at the top of the file, but a statement "
                        f"precedes it: {' '.join(prefix.split())[:120]}",
                    )
                )

    # rule2 / rule3: exports.
    for match in _EXPORT_LINE.finditer(text):
        line = _lineno(text, match.start())
        if name == REGISTER_FILE and _EXPORT_DEFAULT.match(text, match.start()):
            continue  # counted below
        if name == REGISTER_FILE:
            problems.append(
                _violation(
                    name,
                    line,
                    "rule3",
                    "only the single `export default` is allowed here, found: "
                    f"{_snippet(text, match.start())}",
                )
            )
        else:
            problems.append(
                _violation(
                    name,
                    line,
                    "rule2",
                    "export is only allowed as the single `export default` in "
                    f"{REGISTER_FILE}, found: {_snippet(text, match.start())}",
                )
            )

    if name == REGISTER_FILE:
        defaults = len(_EXPORT_DEFAULT.findall(text))
        if defaults != 1:
            problems.append(
                _violation(
                    name,
                    0,
                    "rule3",
                    f"must contain exactly one `export default`, found {defaults}",
                )
            )

    return problems


def render(files: list[Path], texts: list[str]) -> bytes:
    """Assemble header + blocks joined by one blank line; UTF-8, LF, final LF."""
    blocks = []
    for path, text in zip(files, texts):
        block = text.rstrip("\n")
        if not block.strip():
            continue
        blocks.append(block)
    body = "\n\n".join(blocks) + "\n"
    content = HEADER + "\n" + body
    if "\r" in content:  # defensive: normalisation above should prevent this
        raise BuildError(_violation("<output>", 0, "rule6", "carriage return survived assembly"))
    return content.encode("utf-8")


def build(src: Path, out: Path) -> str:
    """Validate + concatenate + write; return the sha256 hex digest."""
    files = discover_sources(src)
    texts = [read_source(path) for path in files]

    problems: list[str] = []
    for path, text in zip(files, texts):
        problems.extend(validate_source(path.name, text, is_core=(path.name == CORE_FILE)))
    if problems:
        raise BuildError(
            f"{len(problems)} rule violation(s) in {src}:\n  "
            + "\n  ".join(problems)
        )

    data = render(files, texts)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(data)

    digest = hashlib.sha256(data).hexdigest()
    print(f"built: {out} from {len(files)} file(s), {len(data)} bytes")
    print(f"sha256: {digest}")
    return digest


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="build.py",
        description="Concatenate desktop/src/*.js into a single deterministic desktop/plugin.js "
        "(MOD-014).",
    )
    parser.add_argument(
        "--src",
        default=str(DEFAULT_SRC),
        help=f"source directory holding *.js parts (default: {DEFAULT_SRC})",
    )
    parser.add_argument(
        "--out",
        default=str(DEFAULT_OUT),
        help=f"output file (default: {DEFAULT_OUT})",
    )
    args = parser.parse_args(argv)

    try:
        build(Path(args.src), Path(args.out))
    except BuildError as exc:
        print(f"build.py: error: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
