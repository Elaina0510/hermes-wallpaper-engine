def test_t10c_no_ctx_timer(tmp_path):
    # NOTE: first-pass check only. Rotation code arrives in T3; this asserts the
    # product is clean *today*, it does not prove future rotation code stays clean.
    text = build_ok(tmp_path / "plugin.js").decode("utf-8")

    assert "ctx.timer" not in text
    assert re.search(r"\bctx\s*\.\s*timer\b", text) is None
    # the legal timer surface is flat and disposer-returning
    assert "ctx.setInterval" in text


