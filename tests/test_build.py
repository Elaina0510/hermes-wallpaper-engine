def test_rule2_import_in_non_core_file_is_rejected(tmp_path):
    src = copy_fixture(tmp_path)
    edit(src / "10-layer.js", "let weLayerEl = null;", 'import { x } from "./x.js";\nlet weLayerEl = null;')

    result = run_build(tmp_path / "plugin.js", src)

    assert_rejected(result, "10-layer.js", "rule2", "./x.js")
    assert not (tmp_path / "plugin.js").exists(), "a failed build must not emit a product"


