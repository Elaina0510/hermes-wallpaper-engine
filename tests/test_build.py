"""T10 / T10b / T10c / T12 — acceptance tests for ``desktop/build.py`` (MOD-014).

Everything is exercised end-to-end through the real CLI (``python build.py``), so
these tests cover exactly what ships. The build input is the fixture tree
``tests/fixtures/build-src/`` — never ``desktop/src/`` — so the tests stay valid
while the real sources (T2.1-T2.7) are still being written.

Anchors (design §12.2):
  T10   two consecutive builds produce the same sha256; import specifiers in the
        product hit only the 4 whitelisted keys.
  T10b  no relative specifier import (static or dynamic) in the product.
  T10c  no ``ctx.timer`` in the product  (first-pass check only: the rotation
        code lands in T3, so this asserts the current product is clean rather
        than proving future rotation code will be).
  T12   ``node --check`` accepts the product once renamed to ``.mjs``.

Run with: python -m pytest tests/test_build.py -v
"""

from __future__ import annotations

import hashlib
import importlib.util
import re
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

TESTS_DIR = Path(__file__).resolve().parent
PLUGIN_ROOT = TESTS_DIR.parent
BUILD = PLUGIN_ROOT / "desktop" / "build.py"
FIXTURE_SRC = TESTS_DIR / "fixtures" / "build-src"

# Design F2 — the loader whitelist is these 4 exact keys, nothing else.
ALLOWED_SPECIFIERS = {
    "@hermes/plugin-sdk",
    "react",
    "react/jsx-runtime",
    "react/jsx-dev-runtime",
}

# Rule 4 — note the em dash (U+2014), same character as the design doc.
HEADER = "// GENERATED by build.py \u2014 do not edit"

SHA_LINE = re.compile(r"(?m)^sha256: ([0-9a-f]{64})\r?$")

# Static import statement in the assembled product.
STATIC_IMPORT = re.compile(
    r"""(?m)^[ \t]*import\s+(?:[^;]*?\bfrom\s*)?["'](?P<spec>[^"'\n]+)["']"""
)
RELATIVE_STATIC_IMPORT = re.compile(
    r"""(?m)^[ \t]*import\b[^;\n]*?\bfrom\s*["']\.{1,2}/"""
)
RELATIVE_DYNAMIC_IMPORT = re.compile(
    r"""\bimport\s*\(\s*(?:/\*[\s\S]*?\*/\s*)?["'`]\.{1,2}/"""
)
RELATIVE_NEW_URL_IMPORT = re.compile(r"""new\s+URL\s*\(\s*["'`]\.{1,2}/""")


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #


def run_build(out: Path, src: Path = FIXTURE_SRC) -> subprocess.CompletedProcess:
    """Invoke the real build CLI with an explicit src/out (no default paths)."""
    return subprocess.run(
        [sys.executable, str(BUILD), "--src", str(src), "--out", str(out)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        cwd=str(TESTS_DIR),
        timeout=120,
    )


def build_ok(out: Path, src: Path = FIXTURE_SRC) -> bytes:
    result = run_build(out, src)
    assert result.returncode == 0, f"build failed:\nstdout={result.stdout}\nstderr={result.stderr}"
    return out.read_bytes()


def sha_from_stdout(stdout: str) -> str:
    matches = SHA_LINE.findall(stdout)
    assert len(matches) == 1, f"expected exactly one sha256 line, got {matches!r} in {stdout!r}"
    return matches[0]


def copy_fixture(tmp_path: Path) -> Path:
    src = tmp_path / "src"
    shutil.copytree(FIXTURE_SRC, src)
    return src


def edit(path: Path, old: str, new: str) -> None:
    text = path.read_text(encoding="utf-8")
    assert old in text, f"{path.name}: anchor {old!r} not found"
    path.write_text(text.replace(old, new, 1), encoding="utf-8")


def assert_rejected(result: subprocess.CompletedProcess, *needles: str) -> None:
    """A rule violation must fail loudly: exit 1 + message naming file and content."""
    assert result.returncode != 0, f"build should have failed, stdout={result.stdout!r}"
    assert result.stderr.strip(), "failure must explain itself on stderr"
    assert "build.py: error:" in result.stderr
    for needle in needles:
        assert needle in result.stderr, f"{needle!r} missing from stderr:\n{result.stderr}"


# --------------------------------------------------------------------------- #
# T10 — determinism + whitelisted specifiers
# --------------------------------------------------------------------------- #


def test_t10_two_runs_identical_sha256(tmp_path):
    first = run_build(tmp_path / "a" / "plugin.js")
    second = run_build(tmp_path / "b" / "plugin.js")

    assert first.returncode == 0, first.stderr
    assert second.returncode == 0, second.stderr

    sha_first = sha_from_stdout(first.stdout)
    sha_second = sha_from_stdout(second.stdout)
    assert sha_first == sha_second, f"non-deterministic build: {sha_first} != {sha_second}"

    bytes_a = (tmp_path / "a" / "plugin.js").read_bytes()
    bytes_b = (tmp_path / "b" / "plugin.js").read_bytes()
    assert bytes_a == bytes_b
    # the printed digest must describe the bytes that actually landed on disk
    assert hashlib.sha256(bytes_a).hexdigest() == sha_first


def test_t10_output_shape_is_utf8_lf_with_header(tmp_path):
    data = build_ok(tmp_path / "plugin.js")
    text = data.decode("utf-8")  # raises if not valid UTF-8

    assert b"\r" not in data, "output must be LF-only"
    assert text.endswith("\n"), "output must end with a single LF"
    assert not text.endswith("\n\n")
    assert text.split("\n", 1)[0] == HEADER
    assert "\u2014" in text.split("\n", 1)[0], "header must use the em dash from the design"


def test_t10_import_specifiers_only_whitelisted(tmp_path):
    text = build_ok(tmp_path / "plugin.js").decode("utf-8")
    specifiers = STATIC_IMPORT.findall(text)

    assert specifiers, "fixture must produce at least one import"
    assert set(specifiers) <= ALLOWED_SPECIFIERS, f"illegal specifiers: {set(specifiers) - ALLOWED_SPECIFIERS}"
    assert set(specifiers) == {"@hermes/plugin-sdk", "react", "react/jsx-runtime"}


def test_t10_single_export_default_at_end(tmp_path):
    text = build_ok(tmp_path / "plugin.js").decode("utf-8")

    assert len(re.findall(r"(?m)^[ \t]*export\s+default\b", text)) == 1
    assert re.search(r"(?m)^[ \t]*export\b", text).start() > text.index("weMountLayer("), (
        "the single export default must come from 99-register.js (last block)"
    )


def test_t10_default_paths_point_into_plugin_tree():
    """Defaults must resolve inside the plugin tree, independent of cwd."""
    spec = importlib.util.spec_from_file_location("we_build_under_test", BUILD)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    assert Path(module.DEFAULT_SRC) == PLUGIN_ROOT / "desktop" / "src"
    assert Path(module.DEFAULT_OUT) == PLUGIN_ROOT / "desktop" / "plugin.js"
    assert module.CORE_FILE == "00-core.js"
    assert module.REGISTER_FILE == "99-register.js"
    assert tuple(module.ALLOWED_SPECIFIERS) == (
        "@hermes/plugin-sdk",
        "react",
        "react/jsx-runtime",
        "react/jsx-dev-runtime",
    )


# --------------------------------------------------------------------------- #
# T10b — no relative specifiers (the loader rejects them, F2)
# --------------------------------------------------------------------------- #


def test_t10b_no_relative_specifier_import(tmp_path):
    text = build_ok(tmp_path / "plugin.js").decode("utf-8")

    static_hits = RELATIVE_STATIC_IMPORT.findall(text)
    assert not static_hits, f"relative static import survives build: {static_hits}"

    dynamic_hits = RELATIVE_DYNAMIC_IMPORT.findall(text)
    assert not dynamic_hits, f"relative dynamic import survives build: {dynamic_hits}"

    url_hits = RELATIVE_NEW_URL_IMPORT.findall(text)
    assert not url_hits, f"`new URL('./...')` specifier survives build: {url_hits}"


def test_t10b_no_sibling_file_names_leak_into_product(tmp_path):
    """No `./10-layer.js`-style reference at all — the product has no siblings."""
    text = build_ok(tmp_path / "plugin.js").decode("utf-8")
    for sibling in ("./00-core.js", "./10-layer.js", "./99-register.js", "../desktop"):
        assert sibling not in text, f"{sibling} must not appear in the product"


