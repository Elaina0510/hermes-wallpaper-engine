def test_t12_node_check_accepts_product(tmp_path):
    node = shutil.which("node")
    if node is None:
        pytest.skip("node not on PATH — T12 syntax check not executed (dev-only tool)")

    mjs = tmp_path / "plugin.mjs"
    mjs.write_bytes(build_ok(tmp_path / "plugin.js"))

    result = subprocess.run(
        [node, "--check", str(mjs)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=120,
    )
    assert result.returncode == 0, f"node --check failed:\n{result.stdout}\n{result.stderr}"


