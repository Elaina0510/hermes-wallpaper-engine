def test_crlf_sources_produce_identical_product(tmp_path):
    lf_src = copy_fixture(tmp_path)
    crlf_src = tmp_path / "src-crlf"
    shutil.copytree(FIXTURE_SRC, crlf_src)
    for path in crlf_src.glob("*.js"):
        path.write_bytes(path.read_bytes().replace(b"\n", b"\r\n"))

    lf_bytes = build_ok(tmp_path / "lf.js", lf_src)
    crlf_bytes = build_ok(tmp_path / "crlf.js", crlf_src)

    assert b"\r" not in crlf_bytes
    assert crlf_bytes == lf_bytes, "CRLF input must normalise to the same LF product"


def test_sources_are_concatenated_in_filename_order(tmp_path):
    text = build_ok(tmp_path / "plugin.js").decode("utf-8")

    assert text.index("weInitialState") < text.index("weMountLayer(") < text.index("weRegister(")
